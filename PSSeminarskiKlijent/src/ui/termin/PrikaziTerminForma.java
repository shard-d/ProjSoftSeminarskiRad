    private void zapamtiTerminActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_zapamtiTerminActionPerformed
        Smena smena = Smena.valueOf((String)smenaCB.getSelectedItem());
        Termin td = new Termin(termin.getIdTermin(), termin.getDatumTermina(), smena, termin.getListaTerminaRadnika());
        boolean signal = TerminKontroler.getInstance().promeniTermin(td);
        if(signal == true){
           Notification.showInfoMessage(this, "Sistem je zapamtio termin");
           new PrikaziTerminTabelaForma().setVisible(true);
           dispose();
           return;
        }
        Notification.showErrorMessage(this, "Sistem nije zapamtio termin");
    }//GEN-LAST:event_zapamtiTerminActionPerformed

    private void dodajButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_dodajButtonActionPerformed
        Radnik radnik = (Radnik)listRadnik.get(radnikCB.getSelectedIndex());
        for(DomainObject i : termin.getListaTerminaRadnika()){
            TerminRadnika t = (TerminRadnika) i;
            if(radnik.equals(t.getRadnik())){
                Notification.showErrorMessage(this, "Radnik je već angažovan za ovaj termin");
                return;
            }
        }
        Uloga uloga = Uloga.valueOf((String)ulogaCB.getSelectedItem());
        termin.getListaTerminaRadnika().add(new TerminRadnika(uloga, napomenaTA.getText(), radnik, termin));  //ja ne znam da li ce ovo raditi
        tabela.setModel(new TerminRadnikaModel(termin.getListaTerminaRadnika()));
    }//GEN-LAST:event_dodajButtonActionPerformed

    private void obrisiButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_obrisiButtonActionPerformed
        int index = tabela.getSelectedRow();
        if(index < 0){ // -1 za neodabrano
            Notification.showErrorMessage(this, "Termin radnika nije izabran");
            return;
        }
        List<DomainObject> list = termin.getListaTerminaRadnika();
        list.remove(index);
        tabela.setModel(new TerminRadnikaModel(termin.getListaTerminaRadnika()));
    }//GEN-LAST:event_obrisiButtonActionPerformed

    private void brisanjeTerminaButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_brisanjeTerminaButtonActionPerformed
        termin.setQueryFilter(new QueryFilter(termin));
        boolean signal = TerminKontroler.getInstance().obrisiTermin(termin);
        if(signal == true){
            Notification.showInfoMessage(this, "Sistem je obrisao termin");
            new PrikaziTerminTabelaForma().setVisible(true);
            dispose();
            return;
        }
        Notification.showErrorMessage(this, "Sistem nije uspeo da obriše termin");
    }//GEN-LAST:event_brisanjeTerminaButtonActionPerformed

