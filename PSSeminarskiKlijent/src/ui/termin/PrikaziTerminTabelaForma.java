    private void primeniButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_primeniButtonActionPerformed
        if(bezKriterijumaRadio.isSelected()){
            terminList = TerminKontroler.getInstance().vratiListuSviTermin();
        }
        
        if(terminIdRadio.isSelected()){
            long id;
            try {
                id = Long.parseLong(terminIdTF.getText());
            } catch (Exception e) {
                Notification.showErrorMessage(this, "Neispravan unos za pretragu termina");
                return;
            }
            Termin ter = new Termin(id, LocalDate.MIN, Smena.PRVA, null);
            ter.setQueryFilter(new QueryFilter(ter));
            terminList = TerminKontroler.getInstance().vratiListuTermin(ter);
        }
        
        // mhm u redu
        if(smenaRadio.isSelected()){
            String value = (String)kriterijumCB.getSelectedItem();
            Smena smena = Smena.valueOf(value);
            Termin td = new Termin(LocalDate.MIN, smena, null);
            td.setQueryFilter(td.generateQueryMask(false, false, true)); // trazi samo po smeni samog sebe (ok)
            terminList = TerminKontroler.getInstance().vratiListuTermin(td);
        }
        if(radnikRadio.isSelected()){
            Termin term = new Termin();
            Radnik z = (Radnik)radnikList.get(kriterijumCB.getSelectedIndex());
            term.setQueryFilter(new QueryFilter(z));
            terminList = TerminKontroler.getInstance().vratiListuTermin(term);
        }
        if(terminList.size() > 0){
            Notification.showInfoMessage(this, "Sistem je pronašao termine po zadatom kriterijumu");
        }else{
            Notification.showErrorMessage(this, "Sistem nije pronašao termine po zadatom kriterijumu");
        }
        tabela.setModel(new TerminTableModel(terminList));
    }//GEN-LAST:event_primeniButtonActionPerformed

