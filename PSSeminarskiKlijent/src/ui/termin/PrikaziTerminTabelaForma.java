    private void pronadjiButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_pronadjiButtonActionPerformed
        int index = tabela.getSelectedRow();
        if(index < 0){
            Notification.showErrorMessage(this, "Termin nije izabran!");
            return;
        }
        Termin stari = (Termin)terminList.get(index);
        stari.setQueryFilter(new QueryFilter(stari));
        Termin novi = (Termin)TerminKontroler.getInstance().pronadjiTermin(stari);
        if(novi == null){
            Notification.showErrorMessage(this, "Sistem nije uspeo da pronađe termin");
            return;
        }
        Notification.showInfoMessage(this, "Sistem je pronašao termin");
        new PrikaziTerminForma(novi).setVisible(true);
        dispose();
    }//GEN-LAST:event_pronadjiButtonActionPerformed

