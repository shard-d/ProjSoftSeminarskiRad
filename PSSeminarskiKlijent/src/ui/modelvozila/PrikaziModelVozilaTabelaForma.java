    private void pronadjiButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_pronadjiButtonActionPerformed
        int index = tabela.getSelectedRow();
        if(index < 0){
            Notification.showErrorMessage(this, "Molimo izaberite model vozila!");
            return;
        }
        ModelVozila izabrano = (ModelVozila)modelvozilalist.get(index);
        izabrano.setQueryFilter(new QueryFilter(izabrano));
        ModelVozila pronadjeno = (ModelVozila)ModelVozilaKontroler.getInstance().pronadjiModelVozila(izabrano);
        if(pronadjeno == null){
            Notification.showErrorMessage(this, "Sistem nije uspeo da pronađe model vozila.");
            return;
        }
        Notification.showInfoMessage(this, "Sistem je pronašao model vozila.");
        new PrikaziModelVozilaForma(pronadjeno).setVisible(true);
        dispose();
    }//GEN-LAST:event_pronadjiButtonActionPerformed

